#ifndef ROBOT_PROTOCOL_MOTION_RESPONSE_RESULT_H
#define ROBOT_PROTOCOL_MOTION_RESPONSE_RESULT_H

#include <stdint.h>

typedef uint8_t MotionResponseResult;

#define MOTION_RESPONSE_OK                0x00U
#define MOTION_RESPONSE_ALREADY_ACTIVE    0x01U
#define MOTION_RESPONSE_ALREADY_ENDED     0x02U
#define MOTION_RESPONSE_SESSION_MISMATCH  0x03U
#define MOTION_RESPONSE_SUPERSEDED        0x04U
#define MOTION_RESPONSE_BUSY_STOPPING     0x05U
#define MOTION_RESPONSE_REJECTED_UNSAFE   0x06U
#define MOTION_RESPONSE_INVALID_COMMAND   0x07U
#define MOTION_RESPONSE_STOP_FAILED       0x08U

#endif